const requireLocal = createRequire(resolve('.dart_tool/adocao_sql_test/package.json'));
const { PGlite } = requireLocal('@electric-sql/pglite');
const migration = await readFile('docs/sql/15_corrigir_exclusao_animal_supabase.sql', 'utf8');
const adoptionMigration = await readFile('docs/sql/10_migrar_adocoes_supabase.sql', 'utf8');
const uids = {
  owner: '11111111-1111-4111-8111-111111111111',
  other: '22222222-2222-4222-8222-222222222222',
  inactive: '33333333-3333-4333-8333-333333333333',
  noProfile: '44444444-4444-4444-8444-444444444444',
};

// PostgreSQL WASM sem rede: apenas registros fictícios e nenhum Supabase.
// IDs integer e grants por coluna refletem o contrato inspecionado; a fixture
// não pretende reproduzir todas as configurações do ambiente de produção.
async function fixture({ withAdoption = false } = {}) {
  const db = new PGlite();
  await db.exec(`
    create role anon nologin;
    create role authenticated nologin;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as
      $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    grant usage on schema public, auth to anon, authenticated;
    grant execute on function auth.uid() to anon, authenticated;
    create table public.cliente (
      id integer primary key,
      auth_user_id uuid unique,
      ativo boolean not null default true,
      nome text not null,
      sobrenome text not null default 'QA',
      email text not null,
      telefone text not null default '11999998888',
      estado text not null default 'SP',
      "cidadeDeResidencia" text not null default 'Cidade ficticia'
    );
    create table public.animal (
      id integer primary key,
      id_cliente integer not null references public.cliente(id),
      ativo boolean not null default true,
      status text not null default 'Disponível',
      nome text not null,
      imagem text,
      idade integer default 2,
      sexo text not null default 'Fêmea'
    );
    create table public.adocao (
      id integer generated by default as identity primary key,
      data timestamptz not null default now(),
      status text not null,
      id_animal integer not null references public.animal(id),
      id_cliente integer not null references public.cliente(id),
      id_dono integer not null references public.cliente(id)
    );
    alter table public.cliente enable row level security;
    alter table public.animal enable row level security;
    alter table public.adocao enable row level security;
    create policy fixture_own_profile on public.cliente for select to authenticated
      using (auth_user_id=auth.uid());
    create policy fixture_read_animal on public.animal for select to anon, authenticated
      using ((ativo and status='Disponível') or
        id_cliente=(select id from public.cliente where auth_user_id=auth.uid()));
    create policy fixture_edit_own_animal on public.animal for update to authenticated
      using (id_cliente=(select id from public.cliente where auth_user_id=auth.uid()))
      with check (id_cliente=(select id from public.cliente where auth_user_id=auth.uid()));
    create policy fixture_delete_own_animal on public.animal for delete to authenticated
      using (id_cliente=(select id from public.cliente where auth_user_id=auth.uid()));
    grant select on public.cliente to anon, authenticated;
    grant select on public.animal to anon, authenticated;
    grant update (nome,imagem,idade) on public.animal to authenticated;
    -- A migração deve revogar DELETE, sem conceder UPDATE em ativo/id_cliente.
    grant delete on public.animal to public, anon, authenticated;
    insert into public.cliente (id,auth_user_id,ativo,nome,email) values
      (1,'${uids.owner}',true,'Responsavel ficticio','owner@example.com'),
      (2,'${uids.other}',true,'Outra pessoa ficticia','other@example.com'),
      (3,'${uids.inactive}',false,'Pessoa inativa ficticia','inactive@example.com');
    insert into public.animal (id,id_cliente,ativo,status,nome,imagem) values
      (10,1,true,'Disponível','Animal disponivel','https://example.com/animal-10.png'),
      (11,1,true,'Adotado','Animal adotado','https://example.com/animal-11.png'),
      (12,1,false,'Disponível','Animal ja inativo','https://example.com/animal-12.png'),
      (20,2,true,'Disponível','Animal de outra pessoa','https://example.com/animal-20.png');
    insert into public.adocao (status,id_animal,id_cliente,id_dono) values
      ('Aguardando',10,2,1),('Aceito',11,2,1);
  `);
  if (withAdoption) await db.exec(adoptionMigration);
  return db;
}

async function actor(db, name, role = 'authenticated') {
  assert.ok(['authenticated', 'anon'].includes(role));
  await db.exec('reset role');
  await db.query("select set_config('request.jwt.claim.sub',$1,true)", [name == null ? '' : uids[name]]);
  await db.exec(`set local role ${role}`);
}

async function rpc(db, id) {
  return (await db.query('select public.excluir_meu_animal($1::bigint) as result', [id])).rows[0].result;
}

async function failure(db, operation, code, message) {
  await db.exec('savepoint expected_failure');
  let error;
  try { await operation(); } catch (caught) { error = caught; }
  await db.exec('rollback to savepoint expected_failure');
  await db.exec('release savepoint expected_failure');
  assert.ok(error, 'Banco deveria recusar a operação.');
  assert.equal(error.code, code, error.message);
  if (message) assert.match(error.message, message);
}

async function data(db) {
  return (await db.query(`select jsonb_build_object(
    'cliente',(select jsonb_agg(to_jsonb(c) order by id) from public.cliente c),
    'animal',(select jsonb_agg(to_jsonb(a) order by id) from public.animal a),
    'adocao',(select jsonb_agg(to_jsonb(d) order by id) from public.adocao d)
  ) as value`)).rows[0].value;
}

async function policies(db) {
  return (await db.query(`select schemaname,tablename,policyname,permissive,roles,cmd,qual,with_check
    from pg_catalog.pg_policies where schemaname='public' order by tablename,policyname`)).rows;
}

async function permissions(db) {
  return (await db.query(`select
    has_table_privilege('authenticated','public.animal','DELETE') as auth_delete,
    has_table_privilege('anon','public.animal','DELETE') as anon_delete,
    has_column_privilege('authenticated','public.animal','ativo','UPDATE') as update_ativo,
    has_column_privilege('authenticated','public.animal','id_cliente','UPDATE') as update_owner,
    has_column_privilege('authenticated','public.animal','nome','UPDATE') as update_nome,
    to_regprocedure('public.excluir_meu_animal(bigint)')::text as rpc`)).rows[0];
}

describe('SQL 15: exclusão lógica segura junto ao SQL 10 em memória', { concurrency: false }, () => {
  let db;
  let originalData;
  let originalPolicies;
  before(async () => {
    db = await fixture({ withAdoption: true });
    originalData = await data(db);
    originalPolicies = await policies(db);
    assert.equal((await permissions(db)).auth_delete, true);
    await db.exec(migration);
  });
  after(async () => { await db?.close(); });
  beforeEach(async () => { await db.exec('begin'); });
  afterEach(async () => { await db.exec('rollback'); });

  it('instala sem alterar registros, RLS ou policies e sem ampliar UPDATE', async () => {
    assert.deepEqual(await data(db), originalData);
    assert.deepEqual(await policies(db), originalPolicies);
    assert.deepEqual(await permissions(db), {
      auth_delete: false, anon_delete: false, update_ativo: false,
      update_owner: false, update_nome: true, rpc: 'excluir_meu_animal(bigint)',
    });
    const flags = await db.query("select relrowsecurity from pg_catalog.pg_class where oid in ('public.cliente'::regclass,'public.animal'::regclass)");
    assert.ok(flags.rows.every((row) => row.relrowsecurity));
  });

  it('próprio animal é desativado com imagem nula e restante/histórico preservados', async () => {
    await actor(db, 'owner');
    assert.deepEqual(await rpc(db, 10), { id: 10, ativo: false });
    await db.exec('reset role');
    const after = await data(db);
    const beforeAnimal = originalData.animal.find((row) => row.id === 10);
    assert.deepEqual(after.animal.find((row) => row.id === 10), { ...beforeAnimal, ativo: false, imagem: null });
    assert.deepEqual(after.adocao, originalData.adocao);
    assert.deepEqual(after.cliente, originalData.cliente);
    assert.equal(after.animal.length, originalData.animal.length);
  });

  it('animal próprio já inativo é idempotente e limpa a imagem remanescente', async () => {
    await actor(db, 'owner');
    assert.deepEqual(await rpc(db, 12), { id: 12, ativo: false });
    assert.deepEqual(await rpc(db, 12), { id: 12, ativo: false });
    await db.exec('reset role');
    const row = (await db.query('select ativo,imagem,status,id_cliente from public.animal where id=12')).rows[0];
    assert.deepEqual(row, { ativo: false, imagem: null, status: 'Disponível', id_cliente: 1 });
  });

  it('animal próprio adotado mantém status, proprietário, IDs e adoção aceita', async () => {
    await actor(db, 'owner');
    assert.deepEqual(await rpc(db, 11), { id: 11, ativo: false });
    await db.exec('reset role');
    const after = await data(db);
    const original = originalData.animal.find((row) => row.id === 11);
    assert.deepEqual(after.animal.find((row) => row.id === 11), { ...original, ativo: false, imagem: null });
    assert.deepEqual(after.adocao, originalData.adocao);
  });

  it('terceiro recebe 404 sem mudar o animal alheio', async () => {
    await actor(db, 'other');
    await failure(db, () => rpc(db, 10), 'PT404', /sem permissão/);
    await db.exec('reset role');
    assert.deepEqual(await data(db), originalData);
  });

  it('papel authenticated sem Auth recebe 401', async () => {
    await actor(db, null);
    await failure(db, () => rpc(db, 10), 'PT401', /Entre novamente/);
  });

  it('anônimo não tem EXECUTE', async () => {
    await actor(db, null, 'anon');
    await failure(db, () => rpc(db, 10), '42501');
  });

  for (const person of ['inactive', 'noProfile']) {
    it(`perfil ${person} recebe 403`, async () => {
      await actor(db, person);
      await failure(db, () => rpc(db, 10), 'PT403', /Perfil não encontrado ou inativo/);
    });
  }

  it('animal ausente recebe 404', async () => {
    await actor(db, 'owner');
    await failure(db, () => rpc(db, 999), 'PT404');
  });

  for (const id of [null, 0, -1]) {
    it(`ID inválido ${id} recebe 400`, async () => {
      await actor(db, 'owner');
      await failure(db, () => rpc(db, id), 'PT400');
    });
  }

  it('UPDATE direto de ativo permanece bloqueado', async () => {
    await actor(db, 'owner');
    await failure(db, () => db.exec('update public.animal set ativo=false where id=10'), '42501');
  });

  it('DELETE direto permanece bloqueado até no próprio animal sem histórico', async () => {
    await actor(db, 'other');
    await failure(db, () => db.exec('delete from public.animal where id=20'), '42501');
  });

  it('alteração direta de proprietário permanece bloqueada', async () => {
    await actor(db, 'owner');
    await failure(db, () => db.exec('update public.animal set id_cliente=2 where id=10'), '42501');
  });

  it('edição dos metadados já autorizados continua funcionando', async () => {
    await actor(db, 'owner');
    await db.exec("update public.animal set nome='Nome ficticio atualizado' where id=10");
    const row = (await db.query('select nome from public.animal where id=10')).rows[0];
    assert.equal(row.nome, 'Nome ficticio atualizado');
  });

  it('RLS preserva o inativo para proprietário e oculta de terceiro', async () => {
    await actor(db, 'owner');
    assert.equal((await db.query('select id from public.animal where id=12')).rows.length, 1);
    await actor(db, 'other');
    assert.equal((await db.query('select id from public.animal where id=12')).rows.length, 0);
  });

  it('ACL da RPC, proprietário privilegiado e search_path estão restritos', async () => {
    const row = (await db.query(`select p.prosecdef,p.proconfig,p.prorettype::regtype::text as result,
      (r.rolsuper or r.rolbypassrls) as privileged,
      has_function_privilege('authenticated',p.oid,'EXECUTE') as authenticated_execute,
      has_function_privilege('anon',p.oid,'EXECUTE') as anon_execute,
      exists(select 1 from aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) acl
        where acl.grantee=0 and acl.privilege_type='EXECUTE') as public_execute
      from pg_catalog.pg_proc p join pg_catalog.pg_roles r on r.oid=p.proowner
      where p.oid='public.excluir_meu_animal(bigint)'::regprocedure`)).rows[0];
    assert.deepEqual(row, {
      prosecdef: true, proconfig: ['search_path=""'], result: 'jsonb', privileged: true,
      authenticated_execute: true, anon_execute: false, public_execute: false,
    });
  });
});

describe('SQL 15: reaplicação e preflights transacionais', { concurrency: false }, () => {
  it('permite a ordem SQL 15 antes do SQL 10 sem perder a RPC ou os grants', async () => {
    const db = await fixture();
    try {
      const original = await data(db);
      await db.exec(migration);
      await db.exec(adoptionMigration);
      assert.deepEqual(await data(db), original);
      assert.equal((await permissions(db)).auth_delete, false);
      assert.equal((await permissions(db)).update_ativo, false);
      await db.exec('begin');
      await actor(db, 'owner');
      assert.deepEqual(await rpc(db, 10), { id: 10, ativo: false });
      await db.exec('rollback');
    } finally { await db.close(); }
  });

  it('funciona sem SQL 10 e pode ser reaplicado sem mudar dados/policies', async () => {
    const db = await fixture();
    try {
      const original = await data(db);
      const originalPolicies = await policies(db);
      await db.exec(migration);
      const firstAcl = await permissions(db);
      await db.exec(migration);
      assert.deepEqual(await data(db), original);
      assert.deepEqual(await policies(db), originalPolicies);
      assert.deepEqual(await permissions(db), firstAcl);
      const count = (await db.query("select count(*)::integer as value from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname='excluir_meu_animal'")).rows[0].value;
      assert.equal(count, 1);
    } finally { await db.close(); }
  });

  for (const scenario of [
    { name: 'overload integer', setup: "create function public.excluir_meu_animal(p_animal_id integer) returns jsonb language sql as $$ select '{}'::jsonb $$", message: /Overload/ },
    { name: 'UPDATE amplo', setup: 'grant update on public.animal to authenticated', message: /UPDATE direto/ },
    { name: 'UPDATE da coluna ativo', setup: 'grant update (ativo) on public.animal to authenticated', message: /UPDATE direto/ },
    { name: 'retorno incompatível', setup: "create function public.excluir_meu_animal(p_animal_id bigint) returns text language sql as $$ select 'nao executar'::text $$", message: /RPC existente incompatível/ },
    { name: 'proprietário sem privilégio', setup: "create function public.excluir_meu_animal(p_animal_id bigint) returns jsonb language sql as $$ select '{}'::jsonb $$; alter function public.excluir_meu_animal(bigint) owner to authenticated", message: /RPC existente incompatível/ },
  ]) {
    it(`${scenario.name} aborta preservando dados e ACL anterior`, async () => {
      const db = await fixture();
      try {
        await db.exec(scenario.setup);
        const original = await data(db);
        const originalAcl = await permissions(db);
        const originalPolicies = await policies(db);
        const originalFunctions = (await db.query("select oid,proacl::text,pg_get_functiondef(oid) as definition from pg_catalog.pg_proc where proname='excluir_meu_animal' order by oid")).rows;
        let error;
        try { await db.exec(migration); } catch (caught) { error = caught; }
        await db.exec('rollback');
        assert.ok(error, 'Preflight deveria abortar a instalação.');
        assert.match(error.message, scenario.message);
        assert.deepEqual(await data(db), original);
        assert.deepEqual(await permissions(db), originalAcl);
        assert.deepEqual(await policies(db), originalPolicies);
        assert.deepEqual((await db.query("select oid,proacl::text,pg_get_functiondef(oid) as definition from pg_catalog.pg_proc where proname='excluir_meu_animal' order by oid")).rows, originalFunctions);
      } finally { await db.close(); }
    });
  }
});
